def _read_manifest(directory: Path) -> dict[str, Any]:
    path = directory / "manifest.json"
    if not path.exists():
        return {}
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    return data if isinstance(data, dict) else {"items": data if isinstance(data, list) else []}


def _existing_items(directory: Path) -> list[dict[str, Any]]:
    items = _read_manifest(directory).get("items", [])
    return [item for item in items if isinstance(item, dict)]


def _command(definition: dict[str, Any], output: Path, ffmpeg: str) -> list[str]:
    lavfi = str(definition["lavfi"]).format(size=FRAME_SIZE, fps=FRAME_RATE)
    # A slow hue drift makes static colour sources feel like motion while still
    # being deterministic and free of any third-party media.
    phase = stable_hash(str(definition["id"]), buckets=360)
    filters = [f"hue=h={phase}+t*12:s=0.55", "eq=contrast=1.15:brightness=-0.04"]
    return [
        ffmpeg,
        "-hide_banner",
        "-loglevel",
        "error",
        "-y",
        "-f",
        "lavfi",
        "-i",
        lavfi,
        "-t",
        str(int(definition["durationSec"])),
        "-vf",
        ",".join([*filters, f"fps={FRAME_RATE}", f"scale={FRAME_SIZE}:flags=lanczos", "format=yuv420p"]),
        "-c:v",
        "libx264",
        "-preset",
        "veryfast",
        "-crf",
        "32",
        "-pix_fmt",
        "yuv420p",
        "-movflags",
        "+faststart",
        "-an",
        str(output),
    ]


def generate_vault_assets(
    directory: Path,
    *,
    ffmpeg: str | None = None,
    force: bool = False,
    definitions: Iterable[dict[str, Any]] = DEFINITIONS,
    timeout_sec: float = 60.0,
) -> list[dict[str, Any]]:
    """Generate (or verify) the CC0 vault and return the manifest items."""
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    ffmpeg = ffmpeg or get_settings().resolved_ffmpeg()

    generated: list[dict[str, Any]] = []
    for definition in definitions:
        asset_id = str(definition["id"])
        output = directory / f"{asset_id}.mp4"
        usable = output.exists() and output.stat().st_size > 1024
        if force or not usable:
            command = _command(definition, output, ffmpeg)
            try:
                result = subprocess.run(
                    command,
                    capture_output=True,
                    text=True,
                    timeout=timeout_sec,
                    check=False,
                )
            except (OSError, subprocess.TimeoutExpired) as exc:
                raise VaultGenerationError(f"could not generate vault asset {asset_id}: {exc}") from exc
            if result.returncode != 0 or not output.exists():
                detail = (result.stderr or "").strip()[-500:]
                raise VaultGenerationError(f"ffmpeg failed for {asset_id}: {detail}")
        generated.append(
            {
                "id": asset_id,
                "title": str(definition["title"]),
                "category": str(definition["category"]),
                "durationSec": int(definition["durationSec"]),
                "license": LICENSE,
                "source": SOURCE,
                "path": output.name,
                "tags": list(definition.get("tags", [])),
                "generatedBy": GENERATOR_ID,
            }
        )

    generated_ids = {item["id"] for item in generated}
    custom = [
        item
        for item in _existing_items(directory)
        if str(item.get("id")) not in generated_ids
    ]
    items = [*generated, *custom]
    manifest = {
        "version": 2,
        "generator": GENERATOR_ID,
        "note": "Generated CC0 loops are runtime files. Custom licensed assets are preserved.",
        "items": items,
    }
    (directory / "manifest.json").write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    return items


def main(argv: list[str] | None = None) -> int:
    """CLI entry point: ``python -m app.vault_assets`` from ``backend/``."""
    parser = argparse.ArgumentParser(description="Generate the CC0 ClipForge gameplay vault")
    parser.add_argument("--dir", type=Path, default=None, help="Vault directory (default: settings.vault_dir)")
    parser.add_argument("--ffmpeg", default=None, help="ffmpeg executable (default: resolved settings value)")
    parser.add_argument("--force", action="store_true", help="Regenerate files that already exist")
    args = parser.parse_args(argv)

    settings = get_settings()
    directory = args.dir or settings.vault_dir
    items = generate_vault_assets(
        directory,
        ffmpeg=args.ffmpeg or settings.resolved_ffmpeg(),
        force=args.force,
    )
    print(f"Generated/verified {len(items)} vault assets in {directory}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
