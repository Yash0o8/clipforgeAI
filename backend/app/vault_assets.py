"""Procedural, copyright-free gameplay vault generator.

The PDF calls for 15–20 loopable background clips. Committing third-party
gameplay would be a licence problem, so ClipForge ships a generator that creates
simple CC0 abstract loops with FFmpeg's built-in ``lavfi`` sources instead. The
generated files are runtime data (ignored by git); only this recipe and the
manifest live in the repository.

Operators can replace any generated entry with their own licensed footage by
editing ``manifest.json``. The generator preserves non-generated entries.
"""

from __future__ import annotations

import argparse
import json
import subprocess
from pathlib import Path
from typing import Any, Iterable

from .config import get_settings
from .utils import stable_hash

GENERATOR_ID = "clipforge-procedural-v1"
LICENSE = "CC0-1.0 (procedurally generated by ClipForge)"
SOURCE = "ClipForge procedural generator — abstract loop, no third-party footage"
FRAME_SIZE = "720x640"  # 1080:960 bottom half of a 9:16 split-screen render
FRAME_RATE = 12


class VaultGenerationError(RuntimeError):
    """Raised when FFmpeg cannot produce a vault asset."""


def _clip(
    asset_id: str,
    title: str,
    category: str,
    duration_sec: int,
    lavfi: str,
    tags: Iterable[str],
) -> dict[str, Any]:
    return {
        "id": asset_id,
        "title": title,
        "category": category,
        "durationSec": duration_sec,
        "lavfi": lavfi,
        "tags": list(tags),
    }


